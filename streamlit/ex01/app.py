# streamlit 라이브러리를 가져와서 st 라는 짧은 이름으로 사용하겠다는 뜻
# 앞으로 나오는 모든 st.xxx() 는 전부 streamlit 이 제공하는 화면 출력 기능
import streamlit as st

# ============================================================
# 1. 기본 텍스트 출력
# ============================================================

# st.title() : 페이지에서 가장 큰 제목 (HTML 의 h1 같은 역할)
st.title("진콩이의 첫 테스트")

# st.write() : 만능 출력 함수
# 문자열, 숫자, 표, 그래프 등 무엇을 넣어도 알아서 형태를 판단해 출력해 줌
st.write("앱 띄우기 성공")

# st.button() : 화면에 버튼을 만들고, "지금 이 순간 눌렸는가?" 를 True/False 로 돌려줌
# 눌린 순간에만 True 가 되므로 if 문과 함께 쓴다
if st.button('눌러보세요'):
    st.balloons()  # 화면에 풍선이 날아가는 효과

# [중요] streamlit 동작 방식
# - 코드의 첫 줄부터 마지막 줄까지 위에서 아래로 한 번 실행되면서 화면이 만들어진다
# - 이벤트(버튼 클릭, 입력값 변경 등)가 발생하면
#   화면을 부분만 고치는 게 아니라 "파일 전체를 처음부터 다시 실행"한다
# - 그래서 버튼을 누르면 아래쪽 코드까지 전부 다시 그려진다

# 섹션(구역) 구분용 제목들 : title > header > subheader 순으로 글자가 작아짐
st.header('헤더출력')
st.subheader('서브헤더 출력')

# st.caption() : 작고 연한 글씨. 보충 설명이나 이미지 설명에 사용
st.caption('캡션 출력')

# st.code() : 코드 블록 형태로 출력 (문법 강조 + 복사 버튼이 자동으로 생김)
# language 옵션으로 어떤 언어인지 알려주면 색깔이 입혀진다
st.code("""
    def hello():
        print('Hello, World!')
""", language='python')


# ============================================================
# 2. 입력 위젯 (사용자가 값을 직접 넣는 것)
# ============================================================
# 모든 입력 위젯은 "사용자가 입력한 값"을 return 한다
# 그래서 name = st.text_input(...) 처럼 변수에 담아서 써야 값을 활용할 수 있다

# 한 줄짜리 텍스트 입력칸
name = st.text_input('이름을 입력하세요')

# 숫자 입력칸
# min_value / max_value : 입력 가능한 최소값·최대값
# step : + - 버튼을 눌렀을 때 한 번에 움직이는 크기
st.number_input('나이를 입력하세요', min_value=0, max_value=100, step=2)

# 달력이 뜨는 날짜 선택칸
st.date_input('날짜를 선택하세요')

# 시간 선택칸
st.time_input('시간을 선택하세요')

# 여러 줄을 입력할 수 있는 큰 입력칸 (자기소개, 리뷰 등)
st.text_area('여러줄의 메시지를 작성하세요')

# 파일 업로드 버튼 (이미지, csv 등을 올릴 수 있음)
st.file_uploader('파일을 업로드하세요')


# ============================================================
# 3. 선택형 입력 위젯
# ============================================================

# 단순 버튼 (위에서 만든 버튼과 별개로 하나 더 생성됨)
st.button('버튼')

# 체크박스 : 켜짐/꺼짐(True/False) 하나를 표현. 여러 개를 동시에 체크 가능
st.checkbox('동의합니다')

# 라디오 버튼 : 여러 항목 중 "딱 하나"만 선택 (예: 성별 선택)
# 선택지는 튜플이나 리스트로 전달
st.radio('옵션 선택', ('옵션1', '옵션2', '옵션3'))

# 셀렉트박스(드롭다운) : 라디오와 똑같이 하나만 선택하지만 목록이 접혀 있음
# 선택지가 많을 때 화면을 아끼기 좋다
st.selectbox('옵션선택', ['옵션1', '옵션2', '옵션3'])

# 멀티셀렉트 : 여러 개를 동시에 고를 수 있음 (선택 결과는 리스트로 반환)
st.multiselect('옵션 선택', ['옵션1', '옵션2', '옵션3'])

# 슬라이더 : 막대를 드래그해서 숫자 선택 (0=시작값, 50=끝값)
st.slider('숫자선택', 0, 50)

# 셀렉트 슬라이더 : 숫자가 아니라 "순서가 있는 값"을 슬라이더로 선택
st.select_slider('평가 선택', ['낮음', '보통', '높음'])


# ============================================================
# 4. 이미지 / 영상 출력
# ============================================================

# st.image(경로, caption=설명, use_container_width=True)
# - "./img.jpg" 는 이 app.py 와 같은 폴더에 있는 img.jpg 를 의미
#   (파일이 없으면 에러가 나니 위치 확인 필요)
# - use_container_width=True : 화면(컨테이너) 너비에 맞춰 이미지 크기 자동 조절
st.image("./img.jpg", caption="손흥민", use_container_width=True)

# st.video('파일경로') 또는 유튜브 주소를 넣으면 영상이 재생된다
# st.video('파일경로')


# ============================================================
# 5. 표(데이터) 출력
# ============================================================

# 1) 표로 만들 데이터 정의
#    딕셔너리의 key = 열(컬럼) 이름, value 리스트 = 그 열의 값들
df = {
    '이름': ['철수', '영희', '민수', '예진'],
    '나이': ['24', '21', '29', '25'],
    "지역": ["서울", "부산", "서울", "광주"]
}

# 2) st.write() : 데이터 모양을 알아서 판단해 표처럼 출력
st.write(df)

# 3) st.dataframe() : 상호작용 가능한 표
#    열 제목을 클릭해 정렬, 검색, csv 다운로드까지 가능 (표가 클 때 유리)
st.dataframe(df)

# 4) st.table() : 기능 없는 정적인 표. 데이터를 전부 그대로 펼쳐서 보여준다
st.table(df)

# st.metric() : 숫자 지표를 강조해서 보여주는 카드
# label=항목 이름, value=현재 값, delta=변화량(양수면 초록 ▲, 음수면 빨강 ▼)
st.metric(label='삼성전자', value='230,000원', delta='2.12%')


# ============================================================
# 6. 차트 출력
# ============================================================
# numpy : 숫자 계산용 라이브러리 / pandas : 표(데이터프레임) 처리용 라이브러리
# 원래 import 는 파일 맨 위에 모아 쓰는 것이 원칙이지만,
# 학습용으로 필요한 위치에 두었다
import numpy as np
import pandas as pd

# np.random.randn(10, 2) : 평균 0 근처의 난수를 10행 2열로 생성
# pd.DataFrame(..., columns=['x','y']) : 그 숫자들을 x, y 열을 가진 표로 변환
random_df = pd.DataFrame(np.random.randn(10, 2), columns=['x', 'y'])

# 데이터프레임만 넘겨주면 streamlit 이 알아서 그래프를 그려준다
st.line_chart(random_df)  # 꺾은선 그래프
st.bar_chart(random_df)   # 막대 그래프


# ============================================================
# 7. 진행 상태 표시
# ============================================================

# st.progress(0) : 0% 상태의 진행바를 화면에 만들고, 그 진행바 객체를 돌려준다
# 이 객체를 변수에 담아두면 나중에 .progress(값) 으로 내용을 갱신할 수 있다
progress_bar = st.progress(0)

import time  # time.sleep() 으로 잠시 멈추기 위해 사용

# range(0, 101, 10) → 0, 10, 20 ... 100
for percent in range(0, 101, 10):
    time.sleep(0.3)                  # 0.3초 대기 (작업하는 척)
    progress_bar.progress(percent)   # 진행바를 percent % 로 갱신

# with st.spinner(...) : with 블록 안의 작업이 끝날 때까지 빙글빙글 로딩 표시
# 시간이 걸리는 작업(파일 읽기, AI 모델 실행 등) 앞뒤로 감싸서 사용
with st.spinner("잠시만 기다려주세요..."):
    time.sleep(3)


# ============================================================
# 8. 상태 메시지 (색깔 있는 알림 박스)
# ============================================================
st.success('완료되었습니다')          # 초록색 - 성공
st.error('에러가 발생했습니다')        # 빨간색 - 실패/오류
st.warning('이 작업은 주의가 필요합니다')  # 노란색 - 경고
st.info('이 작업은 정보표현 부분입니다')   # 파란색 - 안내


# ============================================================
# 9. 화면 레이아웃 (배치)
# ============================================================

# st. 뒤에 sidebar 를 붙이면 그 위젯은 왼쪽 사이드바 영역에 그려진다
# 보통 필터, 설정, 메뉴 같은 것들을 사이드바에 배치한다
st.sidebar.title('사이드바 영역')
st.sidebar.button('버튼')

# st.tabs() : 탭 메뉴 생성
# 탭 이름을 리스트로 넘기면, 탭 개수만큼 객체를 순서대로 돌려준다
tab1, tab2 = st.tabs(['Cat', 'Dog'])

# with tab1: 블록 안에 쓴 내용은 Cat 탭을 눌렀을 때 보인다
with tab1:
    st.image('https://encrypted-tbn0.gstatic.com/images?q=tbn:ANd9GcQbC9Exi4a9vbwNlA1zZMYXHjaxEXuO2Ewqhr8eU5xlaw&s=10.webp')

# with tab2: 블록 안에 쓴 내용은 Dog 탭을 눌렀을 때 보인다
with tab2:
    st.image('https://encrypted-tbn0.gstatic.com/images?q=tbn:ANd9GcSg8NlOY5e2t03XmjVT7Ld6aI6-qzz7wjLhPKDkvkixfQ&s=10')
